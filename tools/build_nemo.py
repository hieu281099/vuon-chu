"""Extract nemo (CC0) SVG shapes into src/gen_nemo.js as recolourable templates.

Hair and beard fills become {C}; glasses strokes become {C}. Faces keep their own colours.
python -I tools/build_nemo.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "vendor" / "nemo" / "x" / "SVG"

def inner(p):
    s = p.read_text(encoding="utf-8")
    s = re.sub(r"^\s*<svg[^>]*>", "", s.strip())
    s = re.sub(r"</svg>\s*$", "", s)
    return re.sub(r"\s+", " ", s).strip()

def templ(s, attr):
    # replace every colour value of the attribute with the {C} placeholder
    return re.sub(attr + r'="(?!none)[^"]*"', attr + '="{C}"', s)

out = {"hairF": {}, "hairB": {}, "faces": {}, "eyes": {}, "mouths": {}, "glasses": {}, "beards": {}}
for f in sorted((SVG / "hairs" / "front").glob("*.black.svg")):
    out["hairF"][f.name.split(".")[0]] = templ(inner(f), "fill")
for f in sorted((SVG / "hairs" / "back").glob("*.black.svg")):
    out["hairB"][f.name.split(".")[0]] = templ(inner(f), "fill")
for f in sorted((SVG / "beards").glob("*.black.svg")):
    out["beards"][f.name.split(".")[0]] = templ(inner(f), "fill")
for f in sorted((SVG / "glasses").glob("*.black.svg")):
    out["glasses"][f.name.split(".")[0]] = templ(inner(f), "stroke")
for f in sorted((SVG / "faces").glob("*.svg")):
    out["faces"][f.stem] = inner(f)
for f in sorted((SVG / "faces" / "parts" / "eyes").glob("*.svg")):
    out["eyes"][f.stem.lower()] = inner(f)
for f in sorted((SVG / "faces" / "parts" / "mouth").glob("*.svg")):
    out["mouths"][f.stem] = inner(f)
js = "/* generated by tools/build_nemo.py from nonemo's CC0 Character Creation Asset Pack */\nconst NEMO = " + json.dumps(out, ensure_ascii=False) + ";\n"
(ROOT / "src" / "gen_nemo.js").write_text(js, encoding="utf-8")
print({k: list(v) for k, v in out.items()}, len(js) // 1024, "KB")
